#!/usr/bin/env node
/**
 * generate-license-report.js (Issue #791)
 *
 * Regenerates the "Production dependency licenses" table in
 * docs/LICENSE_REPORT.md from package-lock.json, so the committed report can
 * never silently drift from the lockfile.
 *
 * Reads only the lockfile (no node_modules, no network): every non-dev entry
 * under `packages` contributes its name, version and `license` field.
 *
 * Usage:
 *   npm run license:report          # rewrite the generated block in place
 *   npm run license:report:check    # exit 1 if the committed block is stale (CI)
 *
 * Options:
 *   --check              Compare instead of writing.
 *   --lockfile <path>    Default: package-lock.json
 *   --report <path>      Default: docs/LICENSE_REPORT.md
 *
 * Exit codes: 0 up to date / written, 1 drift detected, 2 usage or input error.
 */

'use strict';

const fs = require('fs');
const path = require('path');

const BEGIN_MARKER = '<!-- license-report:begin (generated by scripts/generate-license-report.js — do not edit by hand) -->';
const END_MARKER = '<!-- license-report:end -->';

class LicenseReportError extends Error {
  constructor(code, message) {
    super(message);
    this.name = 'LicenseReportError';
    this.code = code;
  }
}

/** Derive the package name from a lockfile `packages` key (handles scopes and nesting). */
function packageNameFromKey(key) {
  const idx = key.lastIndexOf('node_modules/');
  return idx === -1 ? key : key.slice(idx + 'node_modules/'.length);
}

function normaliseLicense(license) {
  if (typeof license === 'string' && license.trim()) return license.trim();
  if (Array.isArray(license) && license.length) {
    return license.map((l) => (typeof l === 'string' ? l : l && l.type) || 'UNKNOWN').join(' OR ');
  }
  if (license && typeof license === 'object' && license.type) return String(license.type);
  return 'UNKNOWN';
}

/**
 * Collect production packages from a parsed lockfile (v2/v3).
 * Returns rows sorted by name then version, de-duplicated on name@version.
 */
function collectProductionPackages(lock) {
  if (!lock || typeof lock !== 'object' || Array.isArray(lock)) {
    throw new LicenseReportError('INVALID_LOCKFILE', 'package-lock.json must contain a JSON object');
  }
  if (!lock.packages || typeof lock.packages !== 'object') {
    throw new LicenseReportError(
      'UNSUPPORTED_LOCKFILE',
      `package-lock.json lockfileVersion ${lock.lockfileVersion ?? 'unknown'} has no "packages" map; regenerate it with npm >= 7`,
    );
  }
  const seen = new Map();
  for (const [key, info] of Object.entries(lock.packages)) {
    if (!key || !info || typeof info !== 'object') continue; // root project entry
    if (info.dev || info.devOptional || info.link) continue;
    const name = info.name || packageNameFromKey(key);
    const version = info.version || 'unknown';
    const id = `${name}@${version}`;
    if (!seen.has(id)) seen.set(id, { name, version, license: normaliseLicense(info.license) });
  }
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

function escapeCell(value) {
  return String(value).replace(/\|/g, '\\|');
}

/** Render the generated Markdown block (between and including the markers). */
function renderReportBlock(rows) {
  const counts = new Map();
  for (const r of rows) counts.set(r.license, (counts.get(r.license) || 0) + 1);
  const summary = [...counts.entries()]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .map(([lic, n]) => `\`${escapeCell(lic)}\` × ${n}`)
    .join(', ');
  const lines = [
    BEGIN_MARKER,
    '',
    `${rows.length} production package(s) resolved from \`package-lock.json\`. Licenses: ${summary || 'none'}.`,
    '',
    '| Package | Version | License |',
    '|---------|---------|---------|',
    ...rows.map((r) => `| \`${escapeCell(r.name)}\` | ${escapeCell(r.version)} | ${escapeCell(r.license)} |`),
    '',
    END_MARKER,
  ];
  return lines.join('\n');
}

/** Replace the generated block inside `markdown`, preserving line endings. */
function replaceReportBlock(markdown, block) {
  const begin = markdown.indexOf(BEGIN_MARKER);
  const end = markdown.indexOf(END_MARKER);
  if (begin === -1 || end === -1 || end < begin) {
    throw new LicenseReportError(
      'MARKERS_MISSING',
      `docs/LICENSE_REPORT.md must contain the generated-block markers:\n  ${BEGIN_MARKER}\n  ${END_MARKER}`,
    );
  }
  const eol = markdown.includes('\r\n') ? '\r\n' : '\n';
  return markdown.slice(0, begin) + block.replace(/\n/g, eol) + markdown.slice(end + END_MARKER.length);
}

/** Compute the expected report; returns `{ current, expected, drift }`. */
function computeReport(lockText, reportText) {
  let lock;
  try {
    lock = JSON.parse(lockText);
  } catch (err) {
    throw new LicenseReportError('INVALID_LOCKFILE', `package-lock.json is not valid JSON: ${err.message}`);
  }
  const expected = replaceReportBlock(reportText, renderReportBlock(collectProductionPackages(lock)));
  const normalise = (s) => s.replace(/\r\n/g, '\n');
  return { current: reportText, expected, drift: normalise(expected) !== normalise(reportText) };
}

function parseArgs(argv) {
  const opts = { check: false, lockfile: 'package-lock.json', report: path.join('docs', 'LICENSE_REPORT.md') };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--check') opts.check = true;
    else if (arg === '--lockfile' || arg === '--report') {
      const value = argv[++i];
      if (!value) throw new LicenseReportError('USAGE', `${arg} requires a path`);
      opts[arg.slice(2)] = value;
    } else throw new LicenseReportError('USAGE', `unknown argument: ${arg}`);
  }
  return opts;
}

function main(argv = process.argv.slice(2), cwd = process.cwd(), out = console) {
  try {
    const opts = parseArgs(argv);
    const lockPath = path.resolve(cwd, opts.lockfile);
    const reportPath = path.resolve(cwd, opts.report);
    for (const p of [lockPath, reportPath]) {
      if (!fs.existsSync(p)) throw new LicenseReportError('FILE_NOT_FOUND', `file not found: ${path.relative(cwd, p)}`);
    }
    const { expected, drift } = computeReport(fs.readFileSync(lockPath, 'utf8'), fs.readFileSync(reportPath, 'utf8'));
    if (opts.check) {
      if (drift) {
        out.error(
          `❌  ${opts.report} is out of date with ${opts.lockfile}.\n` +
            '    Run `npm run license:report` and commit the result.',
        );
        return 1;
      }
      out.log(`✅  ${opts.report} matches ${opts.lockfile}.`);
      return 0;
    }
    if (drift) fs.writeFileSync(reportPath, expected);
    out.log(drift ? `📝  Regenerated ${opts.report}.` : `✅  ${opts.report} already up to date.`);
    return 0;
  } catch (err) {
    if (err instanceof LicenseReportError) {
      out.error(`❌  [${err.code}] ${err.message}`);
      return 2;
    }
    throw err;
  }
}

if (require.main === module) {
  process.exit(main());
}

module.exports = {
  BEGIN_MARKER,
  END_MARKER,
  LicenseReportError,
  collectProductionPackages,
  renderReportBlock,
  replaceReportBlock,
  computeReport,
  main,
};
